package org.jetbrains.app

import jakarta.persistence.EntityManager
import org.springframework.beans.factory.annotation.Autowired
import org.springframework.boot.context.event.ApplicationReadyEvent
import org.springframework.context.event.EventListener
import org.springframework.stereotype.Component
import org.springframework.stereotype.Service
import org.springframework.transaction.annotation.Transactional
import kotlin.time.Clock
import kotlin.time.Duration
import kotlin.time.Duration.Companion.hours
import kotlin.time.Duration.Companion.milliseconds
import kotlin.uuid.Uuid
import java.time.Duration as JDuration
import java.time.Instant as JInstant

@Component
@Transactional
open class Starter @Autowired constructor(
    private val entityManager: EntityManager,
) {

    @EventListener(ApplicationReadyEvent::class)
    fun start() {
        writeDuration(Duration.INFINITE)
        writeDuration(10.hours)

        writeUuidValues()
    }

    fun writeUuidValues() {
        val autoGenerated = GeneratedUuid(
            value = "Created by TestComponent with AUTO",
        )
        val explicitlyGenerated = GeneratedUuidExplicit(
            value = "Created by TestComponent with UUID",
        )

        entityManager.persist(autoGenerated)
        entityManager.persist(explicitlyGenerated)
        entityManager.flush()

        println("AUTO generated UUID: ${autoGenerated.id}")
        println("Explicitly generated UUID: ${explicitlyGenerated.id}")
    }

    fun writeDuration(duration: Duration): Long? {
        val entity = TimeTypes(
            duration = duration,
            instant = Clock.System.now(),
            uuid = Uuid.random(),
            jDuration = JDuration.ofMillis(duration.inWholeMilliseconds),
            jInstant = JInstant.now(),
        )
        entityManager.persist(entity)
        entityManager.flush()
        entityManager.clear()

        return entity.id
    }

}
