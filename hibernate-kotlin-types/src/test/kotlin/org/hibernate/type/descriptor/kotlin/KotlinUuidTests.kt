package org.hibernate.type.descriptor.kotlin

import jakarta.persistence.Column
import jakarta.persistence.Entity
import jakarta.persistence.GeneratedValue
import jakarta.persistence.GenerationType
import jakarta.persistence.Id
import org.hibernate.annotations.JdbcTypeCode
import org.hibernate.type.SqlTypes
import org.hibernate.type.descriptor.java.UUIDJavaType
import org.junit.jupiter.api.Assertions.assertArrayEquals
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertNotEquals
import org.junit.jupiter.api.Assertions.assertNotNull
import org.junit.jupiter.api.Test
import org.junit.jupiter.params.ParameterizedTest
import org.junit.jupiter.params.provider.Arguments
import org.junit.jupiter.params.provider.MethodSource
import java.util.UUID
import kotlin.uuid.Uuid

class KotlinUuidTests : BaseSessionFactoryTest() {
    override val jdbcUrl: String = "jdbc:h2:mem:kotlin-uuid-tests;DB_CLOSE_DELAY=-1"

    override val annotatedClasses: Array<Class<*>> = arrayOf(
        AutoGeneratedUuidEntity::class.java,
        ExplicitGeneratedUuidEntity::class.java,
        DefaultKotlinUuidGeneratedEntity::class.java,
        V4KotlinUuidGeneratedEntity::class.java,
        V7KotlinUuidGeneratedEntity::class.java,
        CharUuidEntity::class.java,
        UuidColumnsEntity::class.java,
    )

    @Test
    fun testAutoGeneration() {
        assertGeneratedIds(AutoGeneratedUuidEntity(), AutoGeneratedUuidEntity()) { it.id }
    }

    @Test
    fun testExplicitGeneration() {
        assertGeneratedIds(ExplicitGeneratedUuidEntity(), ExplicitGeneratedUuidEntity()) { it.id }
    }

    @Test
    fun testKotlinUuidGenerationDefault() {
        assertGeneratedIds(
            DefaultKotlinUuidGeneratedEntity(),
            DefaultKotlinUuidGeneratedEntity(),
            expectedVersion = 4,
        ) { it.id }
    }

    @Test
    fun testKotlinUuidGenerationV4() {
        assertGeneratedIds(
            V4KotlinUuidGeneratedEntity(),
            V4KotlinUuidGeneratedEntity(),
            expectedVersion = 4,
        ) { it.id }
    }

    @Test
    fun testKotlinUuidGenerationV7() {
        assertGeneratedIds(
            V7KotlinUuidGeneratedEntity(),
            V7KotlinUuidGeneratedEntity(),
            expectedVersion = 7,
        ) { it.id }
    }

    @Test
    fun testGenerationForCharColumn() {
        assertGeneratedIds(CharUuidEntity(), CharUuidEntity()) { it.id }
    }

    @ParameterizedTest
    @MethodSource("uuidValues")
    fun testColumnTypesWriteRead(uuid: Uuid?) {
        val loaded = persistAndReload(
            UuidColumnsEntity().apply {
                uuidDefault = uuid
                uuidChar = uuid
                uuidVarchar = uuid
                uuidBinary = uuid
            },
            UuidColumnsEntity::class.java,
        ) { it.id }

        assertEquals(uuid, loaded.uuidDefault)
        assertEquals(uuid, loaded.uuidChar)
        assertEquals(uuid, loaded.uuidVarchar)
        assertEquals(uuid, loaded.uuidBinary)
    }

    @Test
    fun testHqlParameter() {
        val uuid = Uuid.random()
        val row = persistAndReload(
            UuidColumnsEntity().apply { uuidDefault = uuid },
            UuidColumnsEntity::class.java,
        ) { it.id }

        val loadedId = inTransaction { session ->
            session.createSelectionQuery(
                "select id from KotlinUuidColumns where uuidDefault = :value",
                Long::class.javaObjectType,
            ).setParameter("value", uuid).singleResult
        }

        assertEquals(row.id, loadedId)
    }

    @Test
    fun testByteArrayRepresentationMatchesJavaUuid() {
        val value = "01234567-89ab-cdef-fedc-ba9876543210"

        val javaBytes = UUIDJavaType.INSTANCE.unwrap(
            UUID.fromString(value),
            ByteArray::class.java,
            null,
        )
        val kotlinBytes = KotlinUuidJavaType.INSTANCE.unwrap(
            Uuid.parse(value),
            ByteArray::class.java,
            null,
        )

        assertArrayEquals(javaBytes, kotlinBytes)
    }

    private fun <T : Any> assertGeneratedIds(
        first: T,
        second: T,
        expectedVersion: Int? = null,
        id: (T) -> Uuid?,
    ) {
        inTransaction { session ->
            session.persist(first)
            session.persist(second)
            session.flush()
        }

        val firstId = id(first)
        val secondId = id(second)
        assertNotNull(firstId)
        assertNotNull(secondId)
        assertNotEquals(firstId, secondId)
        if (expectedVersion != null) {
            assertEquals(expectedVersion, requireNotNull(firstId).toString()[14].digitToInt())
            assertEquals(expectedVersion, requireNotNull(secondId).toString()[14].digitToInt())
        }

        inTransaction { session ->
            assertNotNull(session.find(first.javaClass, requireNotNull(firstId)))
            assertNotNull(session.find(second.javaClass, requireNotNull(secondId)))
        }
    }

    private companion object {
        @JvmStatic
        fun uuidValues(): List<Arguments> = listOf(
            Arguments.of(null as Uuid?),
            Arguments.of(Uuid.parse("00000000-0000-0000-0000-000000000000")),
            Arguments.of(Uuid.parse("01234567-89ab-cdef-0123-456789abcdef")),
            Arguments.of(Uuid.parse("fedcba98-7654-3210-89ab-cdef01234567")),
            Arguments.of(Uuid.parse("ffffffff-ffff-ffff-ffff-ffffffffffff")),
        )
    }

    @Entity
    open class AutoGeneratedUuidEntity {
        @field:Id
        @field:GeneratedValue
        open var id: Uuid? = null
    }

    @Entity
    open class ExplicitGeneratedUuidEntity {
        @field:Id
        @field:GeneratedValue(strategy = GenerationType.UUID)
        open var id: Uuid? = null
    }

    @Entity
    open class DefaultKotlinUuidGeneratedEntity {
        @field:Id
        @field:KotlinUuidGenerator
        open var id: Uuid? = null
    }

    @Entity
    open class V4KotlinUuidGeneratedEntity {
        @field:Id
        @field:KotlinUuidGenerator(version = KotlinUuidVersion.V4)
        open var id: Uuid? = null
    }

    @Entity
    open class V7KotlinUuidGeneratedEntity {
        @field:Id
        @field:KotlinUuidGenerator(version = KotlinUuidVersion.V7)
        open var id: Uuid? = null
    }

    @Entity
    open class CharUuidEntity {
        @field:Id
        @field:GeneratedValue(strategy = GenerationType.UUID)
        @field:JdbcTypeCode(SqlTypes.CHAR)
        @field:Column(length = 36)
        open var id: Uuid? = null
    }

    @Entity(name = "KotlinUuidColumns")
    open class UuidColumnsEntity {
        @field:Id
        @field:GeneratedValue(strategy = GenerationType.IDENTITY)
        open var id: Long? = null

        open var uuidDefault: Uuid? = null

        @field:JdbcTypeCode(SqlTypes.CHAR)
        @field:Column(length = 36)
        open var uuidChar: Uuid? = null

        @field:JdbcTypeCode(SqlTypes.VARCHAR)
        @field:Column(length = 36)
        open var uuidVarchar: Uuid? = null

        @field:JdbcTypeCode(SqlTypes.BINARY)
        @field:Column(length = 16)
        open var uuidBinary: Uuid? = null
    }
}
